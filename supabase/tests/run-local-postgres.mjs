// Runs the cloud-mirror migrations, synthetic seed, RLS and claim-flow tests against a
// THROWAWAY PostgreSQL cluster created in a temp directory and bound to
// 127.0.0.1 only. It never reads a connection string or credentials from the
// environment, and it checks that the server it connects to reports the
// throwaway cluster's own data directory before applying anything — so it
// cannot target hosted Supabase or any existing database. Type generation
// (--gen-types) uses the Supabase CLI against that same throwaway cluster;
// it does not need Docker, but the first `npx supabase@2.121.0` run downloads
// the CLI (internet required once).
//
//   node supabase/tests/run-local-postgres.mjs [--gen-types <output.ts>]
//
// Requires PostgreSQL server binaries (initdb, pg_ctl, psql). Set PG_BIN to
// their directory if they are not on PATH. Optional PGTEST_PORT (default 54329).
// --gen-types additionally runs `supabase gen types typescript --db-url` against
// the throwaway cluster after the tests pass, writing the generated types.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const supabaseDir = join(here, '..');
const port = Number(process.env.PGTEST_PORT ?? 54329);
const host = '127.0.0.1';

const defaultWindowsBin = 'C:/Program Files/PostgreSQL/17/bin';
const pgBin = process.env.PG_BIN ?? (process.platform === 'win32' && existsSync(defaultWindowsBin) ? defaultWindowsBin : '');
const bin = (name) => (pgBin ? join(pgBin, process.platform === 'win32' ? `${name}.exe` : name) : name);

const genTypesIndex = process.argv.indexOf('--gen-types');
const genTypesOut = genTypesIndex === -1 ? null : process.argv[genTypesIndex + 1];

function run(cmd, args, { allowFail = false, capture = false, detached = false, shell = false } = {}) {
  // `pg_ctl start` leaves the server running with the child's stdio handles;
  // 'ignore' keeps spawnSync from waiting on pipes the server never closes.
  const stdio = detached ? 'ignore' : capture ? 'pipe' : 'inherit';
  const result = spawnSync(cmd, args, { stdio, encoding: 'utf8', shell });
  if (result.error) throw result.error;
  if (result.status !== 0 && !allowFail) {
    throw new Error(`${cmd} ${args.join(' ')} exited with ${result.status}\n${result.stderr ?? ''}`);
  }
  return result;
}

function psqlFile(file) {
  console.log(`-- applying ${file.replace(supabaseDir, 'supabase')}`);
  run(bin('psql'), ['-X', '-q', '-v', 'ON_ERROR_STOP=1', '-h', host, '-p', String(port), '-U', 'postgres', '-d', 'postgres', '-f', file]);
}

const dataDir = mkdtempSync(join(tmpdir(), 'robolime-pgtest-'));
let started = false;
let exitCode = 0;
try {
  run(bin('initdb'), ['-D', dataDir, '-U', 'postgres', '-A', 'trust', '-E', 'UTF8', '--locale=C', '--no-instructions'], { capture: true });
  run(bin('pg_ctl'), ['-D', dataDir, '-l', join(dataDir, 'server.log'), '-w', '-o', `-p ${port} -c listen_addresses=${host}`, 'start'], { detached: true });
  started = true;

  // Safety: prove the server on host:port is the cluster created above before
  // running anything against it (guards against a different server on the port).
  const probe = run(
    bin('psql'),
    ['-X', '-tA', '-h', host, '-p', String(port), '-U', 'postgres', '-d', 'postgres', '-c', 'show data_directory'],
    { capture: true },
  );
  const normalise = (p) => resolve(p.trim()).replace(/\\/g, '/').toLowerCase();
  if (normalise(probe.stdout) !== normalise(dataDir)) {
    throw new Error(`Refusing to continue: server on ${host}:${port} is not the throwaway cluster (${probe.stdout.trim()})`);
  }

  psqlFile(join(here, 'plain_postgres_auth_shim.sql'));
  const migrationsDir = join(supabaseDir, 'migrations');
  for (const file of readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort()) {
    psqlFile(join(migrationsDir, file));
  }
  psqlFile(join(supabaseDir, 'seeds', 'demo_synthetic.sql'));
  psqlFile(join(here, 'rls_robot_scope.test.sql'));
  psqlFile(join(here, 'claim_flow.test.sql'));
  psqlFile(join(here, 'manual_control.test.sql'));

  if (genTypesOut) {
    console.log('-- attempting Supabase type generation against the throwaway cluster');
    const result = run(
      process.platform === 'win32' ? 'npx.cmd' : 'npx',
      ['--yes', 'supabase@2.121.0', 'gen', 'types', 'typescript', '--db-url', `postgresql://postgres@${host}:${port}/postgres?sslmode=disable`, '--schema', 'public'],
      // Windows can only launch npx.cmd through a shell; every argument here is a fixed constant.
      { allowFail: true, capture: true, shell: process.platform === 'win32' },
    );
    if (result.status === 0 && result.stdout.includes('export type Database')) {
      const header = [
        '// GENERATED by `npm run db:cloud:types` (supabase gen types) from the locally validated',
        '// cloud-mirror migrations. Do not edit by hand.',
        '',
      ].join('\n');
      // The CLI emits unformatted output; only trailing whitespace is stripped (no semantic change).
      writeFileSync(genTypesOut, header + result.stdout.replace(/[ \t]+$/gm, ''));
      console.log(`-- wrote generated types to ${genTypesOut}`);
    } else {
      console.error('-- type generation FAILED (BLOCKED):');
      console.error((result.stderr || result.stdout || '').split('\n').slice(0, 8).join('\n'));
      exitCode = 2;
    }
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  exitCode = 1;
} finally {
  if (started) {
    run(bin('pg_ctl'), ['-D', dataDir, '-m', 'fast', '-w', 'stop'], { allowFail: true, capture: true });
  }
  rmSync(dataDir, { recursive: true, force: true });
}
process.exit(exitCode);
