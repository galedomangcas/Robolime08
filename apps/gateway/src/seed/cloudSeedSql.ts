import { fileURLToPath } from 'node:url';

import type { Database } from '../db/connection';
import { allOutboxEntities, cloudRowsFor, type CloudValue } from '../sync/cloudRows';

/** Committed location of the generated cloud demo seed. */
export const CLOUD_SEED_PATH = fileURLToPath(new URL('../../../../supabase/seeds/demo_synthetic.sql', import.meta.url));

function literal(value: CloudValue): string {
  if (value === null) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new RangeError('Non-finite number cannot be exported');
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replace(/'/g, "''")}'`;
  return `'${value.jsonb.replace(/'/g, "''")}'::jsonb`;
}

/**
 * Renders every mirrored entity of a SQLite database as idempotent
 * PostgreSQL INSERTs for the cloud schema. Used to generate the committed
 * synthetic cloud demo seed from the SAME fixture as the SQLite seed, so both
 * stores share identical IDs and values.
 */
export function renderCloudSeedSql(db: Database): string {
  const lines = [
    '-- SYNTHETIC DEMO DATA for the RoboLime cloud mirror. NOT real measurements.',
    '-- GENERATED by `npm run cloud-seed:generate -w @robolime/gateway` from the',
    '-- SQLite demo fixture (apps/gateway/src/seed/demo.ts). Do not edit by hand.',
    '-- Local development databases only. NEVER run against hosted production.',
    '',
    'begin;',
  ];
  for (const { entityType, entityId } of allOutboxEntities(db)) {
    for (const { table, rows } of cloudRowsFor(db, entityType, entityId)) {
      for (const row of rows) {
        const columns = Object.keys(row);
        const values = columns.map((column) => literal(row[column] ?? null));
        lines.push(
          `insert into public.${table} (${columns.join(', ')}) values (${values.join(', ')}) on conflict do nothing;`,
        );
      }
    }
  }
  lines.push('commit;', '');
  return lines.join('\n');
}
